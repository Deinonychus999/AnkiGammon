def _clamp(away: int) -> int:
    return min(max(away, 1), MAX_AWAY)


def met_get(my_away: int, opp_away: int, post_crawford: bool) -> float:
    my_away, opp_away = _clamp(my_away), _clamp(opp_away)
    if post_crawford:
        if opp_away == 1:
            return MET_POST_CRAWFORD[my_away]
        if my_away == 1:
            return 1.0 - MET_POST_CRAWFORD[opp_away]
    return MET[my_away][opp_away]


def met_after_points(my_away: int, opp_away: int, points: int, post_crawford: bool) -> float:
    """The chance after winning (points > 0) or losing (points < 0) points."""
    my_away, opp_away = min(my_away, MAX_AWAY), min(opp_away, MAX_AWAY)
    if points > 0:
        if my_away - points <= 0:
            return 1.0
        return met_get(my_away - points, opp_away, post_crawford)
    if points < 0:
        if opp_away + points <= 0:
            return 0.0
        return met_get(my_away, opp_away + points, post_crawford)
    return met_get(my_away, opp_away, post_crawford)


# A pass HedgeHog stores sits on the win anchor within its quantisation; one
# further away was stored on some other scale and normalizing it means nothing.
PASS_ANCHOR_TOLERANCE = 2e-4


def normalize_cube_triple(
    match_length: int, decider_score: int, other_score: int, cube_value: int,
    no_double: float, double_take: float, double_pass: float,
) -> Optional[Tuple[float, float, float]]:
    """Map a match cube decision's three MWC to normalized equity (losing the
    current cube = -1, cashing it = +1), as HedgeHog displays them.

    Scores are the deciding side's and its opponent's, and `cube_value` is the
    cube before the double. None when HedgeHog would withhold the values.
    """
    if match_length <= 1:
        return None
    my_away = match_length - decider_score
    opp_away = match_length - other_score
    if my_away <= 0 or opp_away <= 0:
        return None
    post_crawford = my_away == 1 or opp_away == 1
    lose = met_after_points(my_away, opp_away, -cube_value, post_crawford)
    win = met_after_points(my_away, opp_away, cube_value, post_crawford)
    span = win - lose
    if span <= 1e-4 or abs(double_pass - win) > PASS_ANCHOR_TOLERANCE:
        return None
    return tuple((mwc - lose) / span * 2.0 - 1.0 for mwc in (no_double, double_take, double_pass))
